/**
 * Print golden movelists for Cubeo scenarios (paste into goldenMovelists.ts or verify).
 *
 *   npx tsx scripts/gen-cubeo-golden.ts
 *   npx tsx scripts/gen-cubeo-golden.ts --write
 */
/* eslint-disable no-console */
import { writeFileSync } from "node:fs";
import { CubeoGame } from "../src/games/cubeo.js";
import { CUBEO_SCENARIOS, type CubeoScenario } from "../test/fixtures/cubeo/scenarios.js";

function movelistFor(scenario: CubeoScenario): string[] {
    const g =
        scenario.state === "fresh"
            ? new CubeoGame(undefined, scenario.variants)
            : new CubeoGame(scenario.state, scenario.variants);
    return [...g.moves()].sort((a, b) => a.localeCompare(b));
}

function main(): void {
    const write = process.argv.includes("--write");
    const entries: Record<string, string[]> = {};
    for (const s of CUBEO_SCENARIOS) {
        const moves = movelistFor(s);
        entries[s.id] = moves;
        console.log(`// ${s.id} — ${s.description}`);
        console.log(JSON.stringify(moves, null, 4));
        console.log("");
    }
    if (write) {
        const body = `/** Generated by \`npx tsx scripts/gen-cubeo-golden.ts --write\`. Do not hand-edit. */\n\nexport const CUBEO_GOLDEN_MOVELISTS: Record<string, string[]> = ${JSON.stringify(entries, null, 4)};\n`;
        writeFileSync("test/fixtures/cubeo/goldenMovelists.ts", body, "utf8");
        console.log("Wrote test/fixtures/cubeo/goldenMovelists.ts");
    }
}

main();
